#!/usr/bin/env python3
"""Generates crates/audiozero-engine/src/soundgineer/data.rs from Soundgineer's own source.

    node --experimental-strip-types scripts/soundgineer/extract.mjs ../soundgineer /tmp/sg.json
    python3 scripts/soundgineer/generate.py /tmp/sg.json > crates/audiozero-engine/src/soundgineer/data.rs
    cargo fmt

The parameter table and the factory presets are read from the TypeScript original, so nothing is
copied by hand. What the Rust port leaves out is listed in README.md ("Soundgineer").
"""
import json, sys

data = json.load(open(sys.argv[1]))
MOD_SLOTS = 16
SHAPE_POINTS = 16   # points in each LFO's drawn curve
OSC_TABLES = ["Basic Shapes", "Harmonic Sweep", "PWM", "Vocal", "FM Bell", "Digital"]

TITLES = {
    "global": "Master", "sub": "Sub", "noise": "Noise", "filterRouting": "Filter routing",
    "dist": "Distortion", "macros": "Macros", "chorus": "Chorus", "phaser": "Phaser",
    "flanger": "Flanger", "delay": "Delay", "reverb": "Reverb", "eq": "EQ", "comp": "Compressor",
    "fxdist": "FX distortion", "matrix": "Matrix",
}
def title(group):
    if group in TITLES: return TITLES[group]
    if group.startswith("lfoshape") and group[8:].isdigit():
        return f"LFO {group[8:]} curve"
    for prefix, name in (("osc", "Osc "), ("filter", "Filter "), ("env", "Env "), ("lfo", "LFO ")):
        if group.startswith(prefix) and group[len(prefix):].isdigit():
            return name + group[len(prefix):]
    return group

def mk(id, name, group, lo, hi, default, step=0, choices=None, unit=""):
    return {"id": id, "name": name, "group": group, "min": lo, "max": hi, "def": default,
            "curve": "lin", "step": step, "choices": choices, "moddable": False, "unit": unit}

params = []
for p in data["params"]:
    if p["id"] == "master.bpm":
        continue  # the song's tempo is used instead
    p = dict(p)
    if p["id"].endswith(".wavetable"):
        p["choices"] = OSC_TABLES; p["max"] = len(OSC_TABLES) - 1  # no custom table
    if p["id"] == "noise.type":
        p["choices"] = ["White", "Pink"]; p["max"] = 1             # no sample slot
    params.append(p)
    if p["id"] == "master.bend_range":
        for pid, name, lo, hi in (("modwheel.value", "Mod wheel", 0, 1), ("pitchbend.value", "Pitch bend", -1, 1), ("aftertouch.value", "Pressure", 0, 1)):
            params.append(mk(pid, name, "global", lo, hi, 0))

sources = ["None"] + [s["name"] for s in data["sources"]]
source_ids = [None] + [s["id"] for s in data["sources"]]
dests = [p for p in params if p["moddable"]]
def dest_label(p):
    if p["group"] == "macros": return p["name"]
    if p["id"] == "master.volume": return "Master volume"
    return f"{title(p['group'])} {p['name']}"
dest_labels = ["None"] + [dest_label(p) for p in dests]
param_index = {p["id"]: i for i, p in enumerate(params)}

first_matrix = len(params)
for n in range(1, MOD_SLOTS + 1):
    params.append(mk(f"mod{n}.source", "Source", "matrix", 0, len(sources) - 1, 0, 1, "SOURCES"))
    params.append(mk(f"mod{n}.dest", "Target", "matrix", 0, len(dest_labels) - 1, 0, 1, "DESTS"))
    params.append(mk(f"mod{n}.depth", "Depth", "matrix", -1, 1, 0))

# Each LFO's drawn curve: how many points it has, then (x, y, bend) for each. The default is
# the triangle every LFO had in the original. Bend is -1 to 1 (0 is a straight line).
first_shape = len(params)
for l in range(1, 9):
    g = f"lfoshape{l}"
    params.append(mk(f"lfo{l}.count", "Points", g, 2, SHAPE_POINTS, 3, 1))
    for i in range(SHAPE_POINTS):
        x = {0: 0.0, 1: 0.5}.get(i, 1.0)
        y = 1.0 if i == 1 else 0.0
        params.append(mk(f"lfo{l}.p{i}x", f"Point {i + 1} x", g, 0, 1, x))
        params.append(mk(f"lfo{l}.p{i}y", f"Point {i + 1} y", g, 0, 1, y))
        params.append(mk(f"lfo{l}.p{i}pow", f"Point {i + 1} bend", g, -1, 1, 0))

def f(x):
    x = float(x)
    s = repr(x)
    return s if ("." in s or "e" in s) else s + ".0"
def lit(s): return json.dumps(s, ensure_ascii=False)

def kind(p):
    if p["choices"] == "SOURCES": return "Kind::Choice(&MOD_SOURCES)"
    if p["choices"] == "DESTS": return "Kind::Choice(&MOD_DEST_LABELS)"
    if p["choices"]: return "Kind::Choice(&[" + ", ".join(lit(c) for c in p["choices"]) + "])"
    if p["step"] and p["min"] == 0 and p["max"] == 1: return "Kind::Toggle"
    if p["step"]: return "Kind::Whole"
    if p["curve"] == "exp": return "Kind::Log"
    return "Kind::Linear"

out = []
w = out.append
w("// @generated by scripts/soundgineer/generate.py from Soundgineer's source. Do not edit by hand.\n")
w("use crate::effects::{Kind, Param};\n")
w("/// Soundgineer's parameters, then the mod matrix's.")
w(f"pub const PARAM_COUNT: usize = {len(params)};")
w(f"pub const MOD_SLOTS: usize = {MOD_SLOTS};")
w(f"/// Where the mod matrix's parameters start: three per slot (source, target, depth).")
w(f"pub const FIRST_MATRIX_PARAM: usize = {first_matrix};")
w("/// Where the LFO curves' parameters start: for each LFO, a point count then (x, y, bend) for each point.")
w(f"pub const FIRST_SHAPE_PARAM: usize = {first_shape};")
w(f"pub const SHAPE_POINTS: usize = {SHAPE_POINTS};\n")
w("/// What can drive a modulation target, with \"None\" first.")
w(f"pub static MOD_SOURCES: [&str; {len(sources)}] = [" + ", ".join(lit(s) for s in sources) + "];\n")
w("/// The ids of the sources, in `MOD_SOURCES` order after \"None\".")
w(f"pub static MOD_SOURCE_IDS: [&str; {len(sources) - 1}] = [" + ", ".join(lit(s) for s in source_ids[1:]) + "];\n")
w("/// What can be modulated, with \"None\" first.")
w(f"pub static MOD_DEST_LABELS: [&str; {len(dest_labels)}] = [" + ", ".join(lit(s) for s in dest_labels) + "];\n")
w("/// The parameter each target (after \"None\") modulates.")
w(f"pub static MOD_DESTS: [usize; {len(dests)}] = [" + ", ".join(str(param_index[p['id']]) for p in dests) + "];\n")
w(f"pub static PARAMS: [Param; {len(params)}] = [")
for p in params:
    w(f"    Param {{ name: {lit(p['id'])}, label: {lit(p['name'])}, min: {f(p['min'])}, max: {f(p['max'])}, default: {f(p['def'])}, unit: {lit(p['unit'])}, kind: {kind(p)} }},")
w("];\n")

sections = []
for i, p in enumerate(params):
    t = title(p["group"])
    if sections and sections[-1][0] == t and sections[-1][2] == i: sections[-1][2] = i + 1
    else: sections.append([t, i, i + 1])
w("/// How the parameters are grouped, in order: a title and the range of `PARAMS`.")
w(f"pub static SECTIONS: [(&str, std::ops::Range<usize>); {len(sections)}] = [")
for t, a, b in sections: w(f"    ({lit(t)}, {a}..{b}),")
w("];\n")

known = {p["id"]: p for p in params}
def clamp(p, v):
    if p["choices"] and p["choices"] not in ("SOURCES", "DESTS"): v = min(v, len(p["choices"]) - 1)
    return max(p["min"], min(p["max"], v))
presets = []
for pr in data["presets"]:
    vals = {}
    for k, v in pr["params"].items():
        if k in known: vals[k] = clamp(known[k], v)
    for i, m in enumerate(pr["mods"][:MOD_SLOTS], 1):
        vals[f"mod{i}.source"] = source_ids.index(m["source"])
        vals[f"mod{i}.dest"] = [p["id"] for p in dests].index(m["dest"]) + 1
        vals[f"mod{i}.depth"] = m["depth"] if m.get("enabled", True) else 0.0
    presets.append((pr["name"], pr["category"].title().replace("Fx / Other", "FX / other"), vals))

w("/// The factory presets: name, category.")
w(f"pub static PRESET_NAMES: [(&str, &str); {len(presets)}] = [")
for n, c, _ in presets: w(f"    ({lit(n)}, {lit(c)}),")
w("];\n")
w("/// A preset's parameters by name; anything it doesn't list is at its default.")
w("pub fn preset(name: &str) -> Option<&'static [(&'static str, f32)]> {")
w("    Some(match name {")
for n, _, vals in presets:
    items = ", ".join(f"({lit(k)}, {f(v)})" for k, v in vals.items())
    w(f"        {lit(n)} => &[{items}],")
w("        _ => return None,")
w("    })")
w("}")
print("\n".join(out))
